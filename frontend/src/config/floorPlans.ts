export type FloorPlan = {
  /**
   * 地圖要畫出來的範圍。整層樓比卡片瘦,照整層畫左右會空一大塊,所以只畫測試用到的
   * 區域,超出的部分由 SVG 裁掉(資料仍完整,方便之後換路徑)。
   */
  view: FloorRect;
  /** 外牆 */
  outline: FloorRect;
  /** 房間 / 隔間 */
  rooms: FloorRect[];
  /** 電梯、樓梯、管道間(畫交叉線) */
  cores: FloorRect[];
  /** 沒有圍成房間的牆線,例如走廊兩側 */
  walls: FloorRect[];
  /** RU 位置 */
  radios: { id: string; x: number; y: number }[];
};

